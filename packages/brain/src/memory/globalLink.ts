/**
 * How a project connects to the user's Global Brain.
 *
 * Two layers, never mixed:
 *   Global Brain    ~/.luci/brain (one per person, shared by every project): preferences and decisions
 *   Project memory  <project>/.luci (one per project): goal, rules, decisions
 *
 * Projects never get their own copies of global preference files, so the live
 * Global Brain is never shadowed by a stale copy. Instead each project gets a
 * generated, read-only summary (.luci/local/global-brain.md) for agents that
 * can't read outside the project folder. It is personal, so local/ keeps it out of git.
 */
import fs from 'node:fs';
import path from 'node:path';
import { MEMORY_FILES, PRODUCT } from '@luci-dev/format';
import { ensureLocalDir, memoryDir } from '../layout/brainLayout.js';
import { DECISION_HISTORY_FILE } from './memoryEngine.js';

/** Files that belong to the Global Brain and must never be copied into a project. */
export const GLOBAL_PREFERENCE_FILES = [
  'design-principles.md', 'coding-preferences.md', 'component-preferences.md', 'workflow-preferences.md',
  'tool-preferences.md', 'lessons-learned.md', 'confirmed-preferences.md', DECISION_HISTORY_FILE
] as const;

const SNAPSHOT_ORDER = [
  'identity.md', 'design-principles.md', 'coding-preferences.md', 'component-preferences.md',
  'workflow-preferences.md', 'tool-preferences.md', 'lessons-learned.md', 'confirmed-preferences.md'
];
const RECENT_DECISIONS = 10;
export const SNAPSHOT_TITLE = '# Global Brain (summary)';

const normalize = (text: string) => text.replace(/^﻿/, '').replace(/\r\n/g, '\n').trim();

/**
 * Write .luci/local/global-brain.md: the user's Global Brain preferences plus their most
 * recent decisions, marked as generated. Returns null when the project has no .luci/.
 */
export function writeGlobalBrainSnapshot(projectDir: string, globalBrainDir: string): { file: string; tokens: number } | null {
  if (!fs.existsSync(memoryDir(projectDir))) return null;

  const parts = [
    SNAPSHOT_TITLE,
    '',
    `_Generated by ${PRODUCT.name} from your Global Brain (\`${globalBrainDir}\`). **Do not edit**: change your Global Brain instead. Refreshed by \`${PRODUCT.command} init\` and \`${PRODUCT.command} start\`. Project rules in \`${PRODUCT.projectDir}/rules.md\` take precedence over everything here._`,
    ''
  ];

  for (const file of SNAPSHOT_ORDER) {
    const full = path.join(globalBrainDir, file);
    if (!fs.existsSync(full)) continue;
    // Shift headings down one level so the summary keeps one top-level title
    const body = normalize(fs.readFileSync(full, 'utf8')).replace(/^(#{1,5}) /gm, '#$1 ');
    if (body) parts.push(body, '');
  }

  const history = path.join(globalBrainDir, DECISION_HISTORY_FILE);
  if (fs.existsSync(history)) {
    const rows = normalize(fs.readFileSync(history, 'utf8')).split('\n').filter(l => /^\|\s*\d{4}-\d{2}-\d{2}/.test(l));
    if (rows.length) {
      parts.push('## Recent decisions', '', '| Date | Category | Decision | Context |', '|---|---|---|---|', ...rows.slice(-RECENT_DECISIONS), '');
    }
  }

  const content = `${parts.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`;
  ensureLocalDir(projectDir);
  const file = path.join(memoryDir(projectDir), MEMORY_FILES.globalBrainSummary);
  fs.writeFileSync(file, content, 'utf8');
  return { file, tokens: Math.round(content.length / 4) };
}
